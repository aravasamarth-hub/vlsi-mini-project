`timescale 1ns/1ps

// ============================================================================
// Module: carry_skip_block_4bit
// Width: 4-bit building block for Carry Skip Adder
// Description:
//   Contains a 4-bit ripple carry section, bit-level propagate generation,
//   group propagate AND-reduction, and 2:1 carry skip multiplexer logic.
// Logic:
//   P[i] = A[i] ^ B[i]
//   Pgroup = P[0] & P[1] & P[2] & P[3]
//   Cout = Pgroup ? Cin : C_ripple
// ============================================================================
module carry_skip_block_4bit (
    input  wire [3:0] A,
    input  wire [3:0] B,
    input  wire       Cin,
    output wire [3:0] SUM,
    output wire       Cout,
    output wire [3:0] P_bits,
    output wire       P_group,
    output wire       C_ripple,
    output wire       Skip_active
);

    wire [4:0] c_int;
    assign c_int[0] = Cin;

    // Bit propagate signals
    assign P_bits[0] = A[0] ^ B[0];
    assign P_bits[1] = A[1] ^ B[1];
    assign P_bits[2] = A[2] ^ B[2];
    assign P_bits[3] = A[3] ^ B[3];

    // Group propagate signal: true if all 4 bits propagate carry
    assign P_group = P_bits[0] & P_bits[1] & P_bits[2] & P_bits[3];

    // 4-stage ripple carry chain inside the block
    genvar i;
    generate
        for (i = 0; i < 4; i = i + 1) begin : gen_fa
            full_adder fa_inst (
                .a   (A[i]),
                .b   (B[i]),
                .cin (c_int[i]),
                .sum (SUM[i]),
                .cout(c_int[i+1])
            );
        end
    endgenerate

    // Ripple carry generated by the 4th stage
    assign C_ripple = c_int[4];

    // Skip decision indicator: active when group propagate is 1 and Cin is active
    assign Skip_active = P_group;

    // Carry Skip Multiplexer:
    // When P_group is 1, incoming carry bypasses the ripple chain directly to Cout
    assign Cout = P_group ? Cin : C_ripple;

endmodule

